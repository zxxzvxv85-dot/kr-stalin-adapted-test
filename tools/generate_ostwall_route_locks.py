"""Block native Ostwall red defections, retaining postwar socialist releases.

Default/--check is read-only; --write patches complete current KR files at their
native paths. No government is changed or restored by a daily watchdog.
"""
from pathlib import Path
import hashlib,json,re
from hoi4_politics_blocks import parse
from kr_generation_baseline import kr_root
ROOT=Path(__file__).resolve().parents[1]
BLOCKED='RUS_ostwall_native_red_routes_blocked'
TAGS=('BAT','LIT','BLR','GEO','AZR')
INPUTS=('events/BAT events (Baltic Duchy).txt','events/LIT events (Lithuania).txt',
        'events/BLR events (White Ruthenia).txt','common/decisions/LIT decisions (Lithuania).txt')

def edits(text,changes):
    for a,z,value in sorted(changes,reverse=True):text=text[:a]+value+text[z:]
    return text
def guard(node,key='trigger'):
    old=node.one(key)
    condition='hidden_trigger = { NOT = { '+BLOCKED+' = yes } }'
    return (old.ia,old.ia,'\n\t\t'+condition) if old else (node.ib,node.ib,'\n\t'+key+' = { '+condition+' }\n')

def render_outputs():
    kr=kr_root(ROOT);out={};manifest={}
    for path in INPUTS:
        raw=(kr/path).read_bytes();text=raw.decode('utf-8-sig');changes=[]
        manifest[path]=hashlib.sha256(raw).hexdigest()
        for root in parse(text):
            if root.k=='country_event':
                if root.value('id') in ('united_baltic_duchy_events.31','lithuania_events.210','belarus_political_events.42'):changes.append(guard(root))
                if root.value('id')=='belarus_political_events.53':
                    a=next(n for n in root.children('option') if n.value('name')=='belarus_political_events.53.a')
                    changes.append(guard(a))
                    b=next(n for n in root.children('option') if n.value('name')=='belarus_political_events.53.b')
                    chance=b.one('ai_chance')
                    assert chance.value('base')=='0' and len(chance.v)==1
                    changes.append((chance.a,chance.b,'ai_chance = { base = 100 modifier = { factor = 0 NOT = { '+BLOCKED+' = yes } } }'))
            if path.startswith('common/decisions/') and isinstance(root.v,list):
                for n in root.v:
                    if n.k=='LIT_start_the_revolution':changes.append(guard(n,'available'))
        assert changes,path
        out[path]=re.sub(r'(?m)^[ \t]+$','',edits(text,changes)).rstrip()+'\n'
    out['common/scripted_triggers/RUS_ostwall_native_routes_triggers.txt']='''# Generated by tools/generate_ostwall_route_locks.py --write
RUS_ostwall_has_red_government = {
    OR = { has_socialist_government = yes has_government = communist }
}
RUS_ostwall_native_red_routes_blocked = {
    OR = { '''+' '.join('original_tag = '+tag for tag in TAGS)+''' }
    NOT = { RUS_ostwall_has_red_government = yes }
    NOT = { AND = { is_subject = yes overlord = { RUS_ostwall_has_red_government = yes } } }
}
'''
    out['common/scripted_effects/RUS_ostwall_native_routes_effects.txt']='''# Generated by tools/generate_ostwall_route_locks.py --write
RUS_ostwall_preserve_native_alignment = {
    if = {
        limit = { RUS_ostwall_native_red_routes_blocked = yes }
        if = {
            limit = { original_tag = BAT }
            clr_country_flag = BAT_AI_collapse
            if = {
                limit = { has_idea = BAT_forest_brothers }
                country_event = united_baltic_duchy_events.41
            }
        }
        # Non-socialist native regimes cannot voluntarily enter the red camp.
        # Socialist postwar releases and subjects of socialist overlords are exempt.
        if = {
            limit = { is_in_faction = yes faction_leader = { RUS_ostwall_has_red_government = yes } }
            leave_faction = yes
        }
    }
}
'''
    out['common/on_actions/RUS_ostwall_native_routes_on_actions.txt']='''# Generated by tools/generate_ostwall_route_locks.py --write
on_actions = {
    on_startup = { effect = { every_country = { limit = { RUS_ostwall_native_red_routes_blocked = yes } RUS_ostwall_preserve_native_alignment = yes } } }
    on_daily = { effect = { RUS_ostwall_preserve_native_alignment = yes } }
    on_join_faction = { effect = { RUS_ostwall_preserve_native_alignment = yes } }
    on_offer_join_faction = { effect = { FROM = { RUS_ostwall_preserve_native_alignment = yes } } }
}
'''
    # GEO and AZR have no native socialist ruling-party switch in these KR files.
    # Their voluntary faction alignment is covered by the shared five-tag guard.
    for path in ('events/GEO events (Georgia).txt','events/AZR events (Azerbaijan).txt'):
        raw=(kr/path).read_bytes();manifest[path]=hashlib.sha256(raw).hexdigest()
        text=raw.decode('utf-8-sig')
        assert not any('ruling_party = '+ideology in text for ideology in ('radical_socialist','syndicalist','totalist','communist')),path
    out['tools/design/ostwall_route_locks_inputs_20261029.json']=json.dumps(manifest,indent=2,ensure_ascii=False)+'\n'
    return out

if __name__=='__main__':
    from generation_io import cli
    # These six country files have their own manifest; the unrelated advisor/
    # ideas comparison baseline must not block or be silently re-recorded here.
    cli(render_outputs,root=ROOT,description=__doc__,kr_dependency=False)
