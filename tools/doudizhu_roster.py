"""Generate the Dou Dizhu roster from the actual Russian character definitions.

The card game can seat the current ruler and unlocked civilian advisers.  It
does not recruit, hire, retire, rename, or modify any character.  Availability
comes from the source character roles, not a separate hard-coded route list.

Primary references:
* installed documentation/triggers_documentation.md: has_character,
  has_country_leader, has_advisor_role, is_political_advisor;
* installed documentation/effects_documentation.md: random_list supports
  variable weights (zero removes a candidate after a draw);
* KR common/scripted_triggers/_character_scripted_triggers.txt: is_dead and
  is_second_in_command;
* vanilla localisation/english/aat_events_l_english.yml: character.GetName.

All functions are read-only.  generate_doudizhu.py owns writing the results.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from zlib import crc32

from hoi4_politics_blocks import N, load, parse

ROOT = Path(__file__).resolve().parents[1]
CIVILIAN_SLOTS = {"political_advisor", "second_in_command"}
# Native unknown-idea marker: 63x63, kept in the same 65x67 adviser area.
# It avoids substituting a different generic person's face for a real ruler.
FALLBACK_PORTRAIT = "GFX_idea_unknown"
# These leaves normally evaluate in the subject character's advisor UI scope.
# Generated country triggers must explicitly scope them back to that person.
CHARACTER_LEAVES = {
    "is_country_leader", "is_second_in_command", "is_hired_as_advisor",
    "has_character_flag", "has_advisor_role", "is_political_advisor",
    "is_dead", "is_character", "is_character_slot",
}
HEADER = "# Generated by tools/doudizhu_roster.py; edit the generator/source characters.\n"


@dataclass(frozen=True)
class Person:
    number: int
    character: str
    source: str
    instances: tuple[N, ...]
    portrait: str
    small: bool

    @property
    def weight(self) -> str:
        return f"RUS_ddz_person_weight_{self.number}"

    @property
    def trigger(self) -> str:
        return f"RUS_ddz_person_{self.number}_eligible"


def _portrait(instance: N) -> tuple[str, bool]:
    portraits = instance.one("portraits")
    if not portraits:
        raise ValueError(f"Missing character portraits: {instance.k}")
    ordered = sorted(portraits.v, key=lambda n: {"civilian": 0, "army": 1, "navy": 2}.get(n.k, 3))
    for role in ordered:
        value = role.value("small")
        if value:
            if not value.startswith("GFX_"):
                raise ValueError(f"Expected existing portrait sprite: {value}")
            return value, True
    # User requested the adviser portrait format throughout.  Do not shrink or
    # crop a large leader painting.  Some ruler/scientist-only entries have no
    # original small portrait; keep their real name and use the native marker.
    return FALLBACK_PORTRAIT, True


def catalogue(root: Path = ROOT) -> tuple[Person, ...]:
    """Stable 19-bit numeric IDs avoid shifting saved seats when a person is added.

    Include army-only characters in the catalogue solely so a military ruler
    is recognised; their eligibility trigger has no adviser alternative.
    """
    definitions: dict[str, tuple[N, Path]] = {}
    for path in sorted((root / "common/characters").glob("RUS*.txt")):
        for top in load(path):
            if top.k == "characters":
                for node in top.v:
                    if node.k.startswith("RUS_"):
                        definitions[node.k] = (node, path)
    result = []
    for key, (node, source) in sorted(definitions.items()):
        instances = tuple(node.children("instance") or [node])
        # A character instance is chosen at country setup; current RUS DLC
        # variants use the same portrait.  Fail if this stops being true.
        images = {_portrait(inst) for inst in instances}
        if len(images) != 1:
            raise ValueError(f"DLC instances need a portrait selector: {key}")
        portrait, small = next(iter(images))
        # Below 524289, including when the engine stores three decimal places.
        number = (crc32(key.encode("utf-8")) & 0x7FFFF) + 1
        result.append(Person(number, key, source.relative_to(root).as_posix(), instances, portrait, small))
    if len({p.number for p in result}) != len(result):
        raise ValueError("Roster numeric ID collision")
    if not result:
        raise ValueError("Russian character sources not found")
    return tuple(result)


def portrait_fallbacks(root: Path = ROOT) -> tuple[str, ...]:
    """Metadata for maintenance notes; never shown as implementation text in UI."""
    return tuple(p.character for p in catalogue(root) if p.portrait == FALLBACK_PORTRAIT)


def _indent(text: str, level: int = 1) -> str:
    return "\n".join("\t" * level + line if line else "" for line in text.splitlines())


def _condition(node: N, character: str) -> str:
    """Move mixed advisor conditions to country scope without changing unlocks.

    Appointment-slot exclusivity is intentionally irrelevant to a card table:
    someone unlocked for a political role can play even when hired elsewhere.
    Explicit checks involving *other* people remain intact, including their
    cabinet appointments, because those can be genuine political unlocks.
    """
    if node.k == "not_already_hired_except_as":
        return "always = yes"
    if node.k in CHARACTER_LEAVES:
        return f"{character} = {{ {node.raw()} }}"
    if node.k.startswith("RUS_") and isinstance(node.v, list):
        return node.raw()  # an explicit character scope already in the source
    if not isinstance(node.v, list):
        return node.raw()
    if node.k in {"has_country_leader", "set_temp_variable", "check_variable"}:
        return node.raw()
    inner = "\n".join(_condition(child, character) for child in node.v)
    return f"{node.k} {node.op} {{\n{_indent(inner)}\n}}"


def _conditions(block: N | None, character: str) -> str:
    return "\n".join(_condition(n, character) for n in block.v) if block else ""


def _role_condition(person: Person, instance: N, role: N) -> str:
    slot = role.value("slot")
    hired = "is_political_advisor" if slot == "political_advisor" else "is_second_in_command"
    unlocked = []
    for block in (instance.one("allowed"), role.one("allowed"), role.one("visible"), role.one("available")):
        text = _conditions(block, person.character)
        if text:
            unlocked.append(text)
    if not unlocked:
        unlocked = ["always = yes"]
    return "\n".join([
        "AND = {",
        f"\t{person.character} = {{ has_advisor_role = {slot} }}",
        "\tOR = {",
        f"\t\t{person.character} = {{ {hired} = yes }}",
        "\t\tAND = {",
        _indent("\n".join(unlocked), 3),
        "\t\t}", "\t}", "}",
    ])


def eligibility(person: Person) -> str:
    alternatives = [
        f"has_country_leader = {{ character = {person.character} ruling_only = yes }}",
        # Cabinet appointments added at runtime are not necessarily present in
        # the original character definition (e.g. Sverdlov in stalin_form_sov.2).
        f"{person.character} = {{ is_political_advisor = yes }}",
        f"{person.character} = {{ is_second_in_command = yes }}",
    ]
    for instance in person.instances:
        for role in instance.children("advisor"):
            if role.value("slot") in CIVILIAN_SLOTS:
                alternatives.append(_role_condition(person, instance, role))
    return "\n".join([
        f"# {person.character} — {person.source}",
        f"{person.trigger} = {{",
        f"\thas_character = {person.character}",
        f"\t{person.character} = {{ NOT = {{ has_character_flag = is_dead }} }}",
        "\tOR = {", _indent("\n".join(alternatives), 2), "\t}", "}",
    ])


def _pick_effect(people: tuple[Person, ...]) -> str:
    lines = [HEADER, "RUS_ddz_pick_people = {",
             "\tset_variable = { RUS_ddz_people_count = 0 }",
             "\tset_variable = { RUS_ddz_people_ready = 0 }"]
    for seat in (1, 2, 3):
        lines.extend([f"\tset_variable = {{ RUS_ddz_person_{seat} = 0 }}",
                      f"\tset_variable = {{ RUS_ddz_portrait_small_{seat} = 0 }}"])
    for person in people:
        lines.extend([
            f"\tset_variable = {{ {person.weight} = 0 }}",
            "\tif = {", f"\t\tlimit = {{ {person.trigger} = yes }}",
            f"\t\tset_variable = {{ {person.weight} = 1 }}",
            "\t\tadd_to_variable = { RUS_ddz_people_count = 1 }", "\t}",
        ])
    lines.extend(["\tif = {", "\t\tlimit = { check_variable = { RUS_ddz_people_count > 2 } }"])
    for seat in (1, 2, 3):
        lines.append("\t\trandom_list = {")
        for person in people:
            lines.extend([
                f"\t\t\t{person.weight} = {{",
                f"\t\t\t\tset_variable = {{ RUS_ddz_person_{seat} = {person.number} }}",
                f"\t\t\t\tset_variable = {{ RUS_ddz_portrait_small_{seat} = {int(person.small)} }}",
                f"\t\t\t\tset_variable = {{ {person.weight} = 0 }}", "\t\t\t}",
            ])
        lines.append("\t\t}")
    lines.extend(["\t\tset_variable = { RUS_ddz_people_ready = 1 }", "\t}"])
    # The scratch weights are unnecessary save data after the table is seated.
    lines.extend(f"\tclear_variable = {person.weight}" for person in people)
    lines.append("}")
    return "\n".join(lines) + "\n"


def _scripted_loc(people: tuple[Person, ...]) -> str:
    lines = [HEADER]
    for seat in (1, 2, 3):
        for suffix in ("Name", "Portrait"):
            lines.extend(["defined_text = {", f"\tname = GetRUSDDZPerson{seat}{suffix}"])
            for person in people:
                key = f"RUS_ddz_roster_{person.number}_name" if suffix == "Name" else person.portrait
                lines.extend([
                    "\ttext = {",
                    f"\t\ttrigger = {{ check_variable = {{ RUS_ddz_person_{seat} = {person.number} }} }}",
                    f"\t\tlocalization_key = {key}", "\t}",
                ])
            fallback = "RUS_ddz_roster_empty" if suffix == "Name" else FALLBACK_PORTRAIT
            lines.extend([f"\ttext = {{ localization_key = {fallback} }}", "}", ""])
    return "\n".join(lines).rstrip() + "\n"


def outputs(root: Path = ROOT) -> dict[str, str]:
    people = catalogue(root)
    result = {
        "common/scripted_effects/RUS_doudizhu_roster.txt": _pick_effect(people),
        "common/scripted_triggers/RUS_doudizhu_roster.txt": HEADER + "\n\n".join(eligibility(p) for p in people) + "\n",
        "common/scripted_localisation/RUS_doudizhu_roster.txt": _scripted_loc(people),
    }
    for language, empty in (("simp_chinese", "等待入座"), ("english", "Empty seat")):
        lines = [f"\ufeffl_{language}:", f' RUS_ddz_roster_empty:0 "{empty}"']
        lines.extend(f' RUS_ddz_roster_{p.number}_name:0 "[{p.character}.GetName]"' for p in people)
        result[f"localisation/{language}/RUS_doudizhu_roster_l_{language}.yml"] = "\n".join(lines) + "\n"
    return result


def check() -> dict[str, int]:
    """Read-only structural and reference invariants for the parent check suite."""
    people = catalogue()
    rendered = outputs()
    for path, content in rendered.items():
        if path.endswith(".txt"):
            parse(content)
    effects = rendered["common/scripted_effects/RUS_doudizhu_roster.txt"]
    assert effects.count("random_list = {") == 3
    assert "RUS_ddz_people_count > 2" in effects
    for person in people:
        assert effects.count(f"{person.weight} = {{") == 3
        assert effects.count(f"set_variable = {{ {person.weight} = 0 }}") == 4
        for seat in (1, 2, 3):
            assert effects.count(f"set_variable = {{ RUS_ddz_person_{seat} = {person.number} }}") == 1
    guards = rendered["common/scripted_triggers/RUS_doudizhu_roster.txt"]
    assert "not_already_hired_except_as" not in guards
    assert "has_advisor_role = high_command" not in guards
    assert "has_advisor_role = army_chief" not in guards
    assert "has_advisor_role = theorist" not in guards
    assert guards.count("ruling_only = yes") == len(people)
    assert all(p.small for p in people)
    return {"characters": len(people), "small_portraits": sum(p.small for p in people),
            "portrait_fallbacks": len(portrait_fallbacks()), "output_files": len(rendered)}


if __name__ == "__main__":
    print(check())
