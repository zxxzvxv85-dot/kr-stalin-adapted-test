def block(key, body):
    return key + ' = {\n' + ''.join('\t' + line + '\n' for line in body.strip().splitlines()) + '}\n'


def eq(name, value):
    return f'check_variable = {{ {P}{name} = {value} }}'


def gt(name, value):
    return f'check_variable = {{ {P}{name} > {value} }}'


def public_card_position(seat, slot, count=20):
    pile = PUBLIC_PILES[seat]
    index = slot - 1
    row = index // pile['columns']
    row_count = max(0, min(pile['columns'], count - row * pile['columns']))
    x = pile['center'] - TABLE_CARD_WIDTH / 2 - (row_count - 1) * pile['step'] / 2 + index % pile['columns'] * pile['step']
    return round(x), pile['y'] + row * pile['row_step']


