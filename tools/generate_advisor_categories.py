def child_blocks(text):
    """Yield direct blocks inside the outer container, preserving original text."""
    tokens = list(re.finditer(r'#[^\n]*|"(?:\\.|[^"\\])*"|[{}=]|[^\s{}=#]+', text))
    tokens = [t for t in tokens if not t[0].startswith('#')]
    depth = 0
    start = key = None
    for i, tok in enumerate(tokens):
        if tok[0] == '{':
            if depth == 1:
                assert tokens[i-1][0] == '='
                key, start = tokens[i-2][0], tokens[i-2].start()
            depth += 1
        elif tok[0] == '}':
            depth -= 1
            assert depth >= 0
            if depth == 1 and start is not None:
                yield key, text[start:tok.end()]
                start = None
    assert depth == 0


def outputs():
    # Match path overrides first, then trait overrides. Never read our own output.
    files = {}
    for source in (KR, ROOT):
        for p in sorted((source/'common/country_leader').glob('*.txt')):
            if p.name != Path(TRAITS).name:
                files[p.name] = p
    traits = {}
    for name, p in sorted(files.items()):
        for key, block in child_blocks(p.read_text(encoding='utf-8-sig')):
            traits[key] = (p, block)
    patched = []
    local_updates = {}
    total = 0
    for key, (p, block) in sorted(traits.items()):
        group = next((i for i, row in enumerate(CATEGORIES, 19) if key.startswith(row[4])), None)
        if group is None:
            continue
        total += 1
        original = block
        # Only presentation changes: identity trait removal/addition remains upstream.
        if re.search(r'\bsprite\s*=', block):
            block, n = re.subn(r'\bsprite\s*=\s*\d+', f'sprite = {group}', block)
            assert n == 1, key
        else:
            pos = block.index('{')+1
            block = block[:pos]+f'\n\t\tsprite = {group}'+block[pos:]
        if p.is_relative_to(ROOT):
            text = local_updates.get(p, p.read_text(encoding='utf-8-sig'))
            assert text.count(original) == 1, key
            local_updates[p] = text.replace(original, block, 1)
        else:
            patched.append('\t'+block)
    assert total > 40, 'Unexpected KR faction trait baseline'
    result = {TRAITS: '# Generated by tools/generate_advisor_categories.py; only sprite changes.\nleader_traits = {\n'+'\n'.join(patched)+'\n}\n'}
    result.update({p.relative_to(ROOT).as_posix(): text for p,text in local_updates.items()})
    # Retain every KR card widget. Reserve two rows for faction + native filters.
    gui = (KR/'interface/command_character_view.gui').read_text(encoding='utf-8-sig')
    assert 'name = "command_character_view_filter_button"' not in gui, 'KR now supplies the template: review compatibility patch'
    assert gui.count('position = { x = 0 y = 98 }') == 1
    gui = gui.replace('position = { x = 0 y = 98 }', 'position = { x = 0 y = 143 }')
    assert gui.count('size = { width=100% height=50 }') == 1
    gui = gui.replace('size = { width=100% height=50 }', 'size = { width=100% height=95 }')
    gui = gui.replace('max_slots_horizontal = 8', 'max_slots_horizontal = 10')
    # Isolated native template, also available on older KR versions.
    result['interface/command_character_view.gui'] = '# Generated from installed KR; see tools/ADVISOR_CATEGORIES.md.\n'+gui
    result['interface/zz_RUS_advisor_categories.gfx'] = '''spriteTypes = {
    SpriteType = {
        name = "GFX_idea_traits_strip"
        texturefile = "gfx/interface/ideas/RUS_advisor_categories.png"
        noOfFrames = 27
    }
}
'''
    for language, column in [('simp_chinese',1),('english',2),('russian',3)]:
        result[f'localisation/replace/RUS_advisor_categories_l_{language}.yml'] = f'l_{language}:\n'+''.join(f' ADVISOR_CATEGORY_{i}: "{row[column]}"\n' for i,row in enumerate(CATEGORIES,19))
    return result, total


def assets(write):
    source = KR/'gfx/interface/ideas/idea_traits_strip.dds'
    paths = [source]+[ART/(row[0]+'.png') for row in CATEGORIES]
    hashes = {str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else 'KR/idea_traits_strip.dds': hashlib.sha256(p.read_bytes()).hexdigest() for p in paths}
    record = ART/'atlas_hashes.json'
    if write:
        from PIL import Image
        original = Image.open(source).convert('RGBA')
        assert original.size == (828,46)
        image = Image.new('RGBA',(27*46,46))
        image.paste(original,(0,0))
        for i,p in enumerate(paths[1:],18):
            icon=Image.open(p).convert('RGBA')
            assert icon.size == (46,46)
            image.paste(icon,(46*i,0))
        target=ROOT/ATLAS;target.parent.mkdir(parents=True,exist_ok=True);image.save(target)
        hashes[ATLAS]=hashlib.sha256(target.read_bytes()).hexdigest()
        record.write_text(json.dumps(hashes,indent=2)+'\n',encoding='utf-8')
    else:
        hashes[ATLAS]=hashlib.sha256((ROOT/ATLAS).read_bytes()).hexdigest()
        assert hashes == json.loads(record.read_text(encoding='utf-8')), 'Stale atlas or artwork; review before --write --assets'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    mode=parser.add_mutually_exclusive_group()
    mode.add_argument('--write',action='store_true');mode.add_argument('--check',action='store_true')
    parser.add_argument('--assets',action='store_true')
    args=parser.parse_args()
    assert not args.assets or args.write, '--assets requires --write'
    data,count=outputs();stale=[]
    for name,text in data.items():
        p=ROOT/name
        if args.write:
            p.parent.mkdir(parents=True,exist_ok=True)
            p.write_text(text,encoding='utf-8-sig' if name.endswith('.yml') else 'utf-8',newline='\n')
        elif not p.exists() or p.read_text(encoding='utf-8-sig') != text:
            stale.append(name)
    assets(args.assets)
    assert not stale, 'Stale generated files: '+', '.join(stale)
    print(f'PASS: {count} identity traits; 9 faction categories; original 18 categories retained; '+('written' if args.write else 'read-only check'))


if __name__ == '__main__':
    main()
