"""Explicit 20-PP original-republic restoration, independent of old target arrays.

Default/--check is read-only; --write updates only the controlled additions.
The actual conversion reuses the existing original-republic native effects.
"""
from pathlib import Path
import json,re
from hoi4_politics_blocks import parse,load
ROOT=Path(__file__).resolve().parents[1]
TAGS=('BAT','EST','LAT','LIT','BLR','UKR','GEO','AZR','ARM','KAZ','TRK','KHI','BUK')
DECISION='RUS_reconstruct_original_republic'
TARGET='RUS_is_reconstruction_republic_target'
ELIGIBLE='RUS_reconstruction_republic_eligible'
DEC=Path('common/decisions/RUS_reconstruction_republic_decisions.txt')
FX=Path('common/scripted_effects/RUS_reconstruction_republic_effects.txt')
TR=Path('common/scripted_triggers/RUS_reconstruction_republic_triggers.txt')
NATIVE=Path('common/decisions/RUS decisions (Russia).txt')
FOCUS=Path('common/national_focus/00_RUS_future_foreign_policy_skeleton.txt')
def patch(text,edits):
    for a,b,value in sorted(edits,reverse=True):text=text[:a]+value+text[b:]
    return text
def render_outputs():
    out={};text=(ROOT/NATIVE).read_text(encoding='utf-8-sig')
    original=next(n for c in parse(text) if isinstance(c.v,list) for n in c.v if n.k=='RUS_add_to_soviet_republic')
    # Remove only the thirteen explicitly restored targets from the generic cheap
    # decision; Mongolia and all unrelated old/new union decisions retain rules.
    trigger=original.one('target_trigger');condition='FROM = { NOT = { '+TARGET+' = yes } }'
    if TARGET not in trigger.raw():text=patch(text,[(trigger.ib,trigger.ib,'\n\t\t\t'+condition+'\n\t\t')])
    updated=next(n for c in parse(text) if isinstance(c.v,list) for n in c.v if n.k=='RUS_add_to_soviet_republic').one('target_trigger')
    text=patch(text,[(updated.a,updated.b,re.sub(r'(?m)^[ \t]+$','',updated.raw()))])
    out[str(NATIVE).replace('\\','/')]=text
    body='\n'.join(n.raw() for n in original.one('complete_effect').v if n.k!='log')
    register='''
hidden_effect = {
    if = {
        limit = { NOT = { is_in_array = { RUS_SSTR_tags = FROM } } }
        add_to_array = { array = RUS_SSTR_tags value = FROM }
    }
}
'''
    out[str(FX).replace('\\','/')]='# Generated by tools/generate_reconstruction_republic_decisions.py --write\nRUS_reconstruct_original_republic_effect = {\n'+body+register+'}\n'
    out[str(TR).replace('\\','/')]='''# Generated by tools/generate_reconstruction_republic_decisions.py --write
RUS_is_reconstruction_republic_target = {
    OR = { '''+' '.join('tag = '+tag for tag in TAGS)+''' }
}
RUS_reconstruction_republic_eligible = {
    exists = yes
    hidden_trigger = { RUS_is_reconstruction_republic_target = yes }
    is_subject_of = ROOT
    NOT = { has_autonomy_state = soviet_socialist_republic }
    OR = { has_socialist_government = yes has_government = communist }
}
'''
    out[str(DEC).replace('\\','/')]='''# Generated by tools/generate_reconstruction_republic_decisions.py --write
RUS_Spreading_the_Revolution_decisions = {
    RUS_reconstruct_original_republic = {
        icon = GFX_decision_generic_flags
        targets = { '''+' '.join(TAGS)+''' }
        target_root_trigger = {
            original_tag = RUS
            has_completed_focus = RUS_future_foreign_014
            OR = { has_socialist_government = yes has_government = communist }
        }
        target_trigger = {
            RUS_europe_intervention_target_selected_or_overview = yes
            FROM = { RUS_reconstruction_republic_eligible = yes }
        }
        visible = {
            has_completed_focus = RUS_future_foreign_014
            NOT = { has_country_flag = RUS_europe_intervention_molotov_selected }
            NOT = { has_country_flag = RUS_europe_intervention_filter_active }
            RUS_europe_intervention_target_selected_or_overview = yes
            FROM = { NOT = { has_autonomy_state = soviet_socialist_republic } }
        }
        available = {
            FROM = { RUS_reconstruction_republic_eligible = yes }
            RUS_diplomacy_can_pay_20 = yes
        }
        cost = RUS_diplomacy_pp_cost_20?20
        fire_only_once = yes
        complete_effect = {
            if = {
                limit = { FROM = { RUS_reconstruction_republic_eligible = yes } }
                RUS_reconstruct_original_republic_effect = yes
            }
            else = { RUS_diplomacy_refund_20 = yes }
        }
        ai_will_do = { base = 0 }
    }
}
'''
    text=(ROOT/FOCUS).read_text(encoding='utf-8-sig')
    f=next(n for n in parse(text) if n.value('id')=='RUS_future_foreign_014')
    reward=f.one('completion_reward')
    if DECISION not in reward.raw():
        # Native read-only previews name all thirteen targets; actual availability
        # comes from target_root_trigger and is valid for future releases too.
        preview='\n\t\teffect_tooltip = {\n'+''.join('\t\t\tactivate_targeted_decision = { target = '+tag+' decision = '+DECISION+' }\n' for tag in TAGS)+'\t\t}\n\t'
        text=patch(text,[(reward.ib,reward.ib,preview)])
    updated=next(n for n in parse(text) if n.value('id')=='RUS_future_foreign_014').one('completion_reward')
    text=patch(text,[(updated.a,updated.b,re.sub(r'(?m)^[ \t]+$','',updated.raw()))])
    out[str(FOCUS).replace('\\','/')]=text
    titles={
        'simp_chinese':('恢复[FROM.GetNameDef]的加盟共和国地位','确认共和国在联盟中的地位。'),
        'english':('Restore [FROM.GetNameDef] as a Union Republic','Confirm the republic’s place within the Union.'),
        'russian':('Восстановить [FROM.GetNameDef] в качестве союзной республики','Закрепить место республики в составе Союза.')}
    for lang,(title,desc) in titles.items():
        values={DECISION:title,DECISION+'_desc':desc}
        out[f'localisation/{lang}/RUS_reconstruction_republic_l_{lang}.yml']='l_'+lang+':\n'+''.join(' '+k+':0 '+json.dumps(v,ensure_ascii=False)+'\n' for k,v in values.items())
    return out

if __name__=='__main__':
    from generation_io import cli
    cli(render_outputs,root=ROOT,description=__doc__,kr_dependency=False)
