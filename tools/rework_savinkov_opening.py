def render_legacy_tree():
    text=read(F);tree=node(text);spans=[]
    for f in tree.children('focus'):
        if f.value('id') in set(SPEC['focuses'])|set(SPEC['retired_focuses']):spans.append((f.a,f.b,''))
        else:
            # A child allow_branch overrides inherited route visibility. The
            # former per-node NOT-natpop gates exposed every route afterwards.
            # Remove only that marked addition, preserving all original fields.
            raw=re.sub(r'[ \t]*# Savinkov opening: only the ten approved focuses are visible\.\s*NOT\s*=\s*\{\s*has_government\s*=\s*national_populist\s*\}', '',f.raw())
            if f.value('id') not in LATER_BASELINE['explicit_allow_branch']:
                raw=edits(raw,[(b.a,b.b,'') for b in node(raw).children('allow_branch') if not b.v])
            if raw!=f.raw():spans.append((f.a,f.b,raw))
    text=edits(text,spans)
    begin='\t# BEGIN approved Savinkov opening shared focuses';end='\t# END approved Savinkov opening shared focuses'
    # The live later tree must not import the opening's ten shared focuses.
    # The separate opening tree is selected/loaded directly; route transition
    # keeps completed state and buffs without attaching its nodes here again.
    if begin in text:text=re.sub(re.escape(begin)+r'.*?'+re.escape(end)+r'\s*\n','',text,count=1,flags=re.S)
    return text

