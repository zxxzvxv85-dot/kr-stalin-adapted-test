def read(p,fallback=None):
    path=ROOT/p
    return path.read_text(encoding='utf-8-sig') if path.exists() else fallback.read_text(encoding='utf-8-sig')

def node(text): return parse(text)[0]

def edits(text,spans):
    expanded=[]
    for a,b,new in spans:
        if not new:
            start=text.rfind('\n',0,a)+1;end=text.find('\n',b)
            if end<0:end=len(text)
            if not text[start:a].strip() and not text[b:end].strip():a,b=start,min(end+1,len(text))
        expanded.append((a,b,new))
    for a,b,new in sorted(expanded,reverse=True):text=text[:a]+new+text[b:]
    return text

def clean_block(text):return re.sub(r'[ \t]+$', '',text,flags=re.M)

def fields(raw,values,remove=()):
    n=node(raw);changes=[]
    for key in set(values)|set(remove):
        ns=n.children(key)
        for i,c in enumerate(ns):changes.append((c.a,c.b,values.get(key,'') if i==0 else ''))
        if not ns and key in values:changes.append((n.ib,n.ib,'\n\t'+values[key]+'\n'))
    return clean_block(edits(raw,changes))

def append_field(raw,key,extra):
    n=node(raw);c=n.one(key)
    if c:return clean_block(raw[:c.ib]+'\n'+extra+'\n'+raw[c.ib:])
    return clean_block(raw[:n.ib]+f'\n\t{key} = {{\n{extra}\n\t}}\n'+raw[n.ib:])

def replace_blocks(text,key,callback):
    return edits(text,[(n.a,n.b,callback(n)) for n in parse(text) if n.k==key])

def indent(raw,level=1):return textwrap.indent(textwrap.dedent(raw).strip(),'\t'*level)

