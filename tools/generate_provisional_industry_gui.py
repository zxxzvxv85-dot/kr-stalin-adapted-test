"""A visual filter for existing industrial projects, not another economic system.

Native references: RUS_education_dashboard (decision_category context); vanilla
countryconstructionsview.gfx (alpha hit testing); KR Russian industrial decisions.
No artwork is generated or repainted by this text generator.
"""
from pathlib import Path
import re
from hoi4_politics_blocks import parse
from generation_io import cli

ROOT = Path(__file__).resolve().parents[1]
CATEGORY = 'RUS_first_five_year_plan_industrial_projects'
DECISIONS = 'common/decisions/RUS decisions (Russia).txt'
CATEGORIES = 'common/decisions/categories/RUS decision_cats (Russia).txt'
ART = 'gfx/interface/RUS_provisional_industry'
ROADS = {'RUS_improve_roads_in_central_russia', 'RUS_improve_roads_in_northern_russia', 'RUS_improve_roads_in_the_volga_basin'}
RAILS = {'RUS_northern_route', 'RUS_upgrade_the_railroad_chelyabinsk', 'RUS_upgrade_the_railroad_krasnoyarsk', 'RUS_upgrade_the_railroad_vladivostok', 'RUS_central_asia_railroads'}
# Game coordinates. Alpha silhouettes, not their overlapping bounds, are used
# for hit testing and native hover tint, not four rectangular picture buttons.
ZONES = [('relief', 1, 24, 181, 132, 93), ('factory', 2, 177, 67, 286, 208),
         ('rail', 3, 76, 275, 220, 76), ('road', 4, 317, 234, 153, 117)]

def block(key, body): return key + ' = {\n' + body + '\n}\n'
def find(text, key): return next(n for n in parse(text) if n.k == key)

def decision_patch(text):
    # Idempotent marked, narrowly-scoped additions; preserve every native reward,
    # gate, target, AI weight, timer, cancellation and cost byte for byte.
    text = re.sub(r'\n[ \t]*# RUS_RECOVERY_FILTER_BEGIN.*?# RUS_RECOVERY_FILTER_END\n', '', text, flags=re.S)
    text = re.sub(r'\n[ \t]*# RUS_RECOVERY_OVERVIEW_BEGIN.*?# RUS_RECOVERY_OVERVIEW_END\n', '', text, flags=re.S)
    category = find(text, CATEGORY)
    edits, groups = [], {}
    for n in category.v:
        if not isinstance(n.v, list) or n.one('days_mission_timeout') or n.value('selectable_mission') == 'no':
            continue
        selected = 4 if n.k in ROADS else 3 if n.k in RAILS else 2
        groups[n.k] = [selected] + ([1] if 'RUS_decrease_black_monday = yes' in n.raw() else [])
        condition = 'RUS_rc_show_' + n.k + ' = yes'
        marker = '\n\t\t# RUS_RECOVERY_FILTER_BEGIN\n\t\t' + condition + '\n\t\t# RUS_RECOVERY_FILTER_END\n'
        vis = n.one('visible')
        if vis: edits.append((vis.ia, vis.ia, marker))
        else: edits.append((n.ia,n.ia, '\n\t\t# RUS_RECOVERY_FILTER_BEGIN\n\t\tvisible = { ' + condition + ' }\n\t\t# RUS_RECOVERY_FILTER_END\n'))
    # Keeps the category present when the selected filter has no unlocked project.
    overview = '''
    # RUS_RECOVERY_OVERVIEW_BEGIN
    RUS_rc_overview = {
        icon = GFX_decision_generic_construction
        allowed = { original_tag = RUS }
        visible = { RUS_rc_provisional_phase = yes }
        cost = 0
        ai_will_do = { base = 0 }
        complete_effect = { hidden_effect = { set_variable = { RUS_rc_filter = 0 } } }
    }
    # RUS_RECOVERY_OVERVIEW_END
'''
    edits.append((category.ia, category.ia, overview))
    for a,b,v in sorted(edits, reverse=True): text=text[:a]+v+text[b:]
    return text, groups

def category_patch(text):
    c = find(text,CATEGORY)
    if c.one('scripted_gui'):
        if c.value('scripted_gui') != 'RUS_rc_dashboard': raise ValueError('Another GUI owns industrial projects')
        return text
    picture = c.one('picture')
    if not picture: raise ValueError('Expected original industrial category picture')
    return text[:picture.a] + 'scripted_gui = RUS_rc_dashboard' + text[picture.b:]

