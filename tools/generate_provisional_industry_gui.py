    loc = {
      'RUS_rc_title':'临时政府 · 工业复兴委员会',
      'RUS_rc_status':'黑色星期一：[RUSRecoverySeverity]',
      'RUS_rc_selection':'当前查看：[RUSRecoverySelection]',
      'RUS_rc_all':'全部工程', 'RUS_rc_relief':'经济救济', 'RUS_rc_factory':'工业恢复', 'RUS_rc_rail':'铁路建设', 'RUS_rc_road':'道路工程',
      'RUS_rc_overview':'显示全部工业工程',
      'RUS_rc_overview_desc':'查看所有已解锁的工业与交通建设工程。',
      'RUS_rc_relief_tt':'§Y经济救济§!\\n查看能够缓解黑色星期一的工程。',
      'RUS_rc_factory_tt':'§Y工业恢复§!\\n查看厂房、能源与资源开发工程。',
      'RUS_rc_rail_tt':'§Y铁路建设§!\\n查看铁路扩建工程。\\n相关国策：§Y国民经济普查§!。',
      'RUS_rc_road_tt':'§Y道路工程§!\\n查看道路建设工程。\\n相关国策：§Y为发展奠基§!。',
      'RUS_rc_clear':'§G无危机修正§!',
    }
    for i in range(1,7):loc[f'RUS_rc_crisis_{i}']=f'§Y第{i}级§! / 6'
    sloc=block('defined_text','name = RUSRecoverySelection\n'+''.join(block('text',f'trigger = {{ check_variable = {{ RUS_rc_filter = {i} }} }} localization_key = RUS_rc_{k}') for k,i,*_ in ZONES)+'text = { localization_key = RUS_rc_all }')
